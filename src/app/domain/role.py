"""Ролевая модель проекта.

Вынесена в отдельный модуль, а не оставлена рядом с `User`, потому что на роли
ссылаются три независимых места: жизненный цикл проблемы (кому доступен
Acknowledge), маршрутизация (умолчания подписок) и авторизация (claim `role` в
токене). Если бы перечень жил в `user.py`, то `problem.py` пришлось бы
импортировать пользователя ради одной проверки — и получился бы цикл.
"""

from enum import StrEnum


class Role(StrEnum):
    """Четыре роли, больше не заводить.

    Излишне сложная ролевая модель прямо названа риском проекта (п. 10 ТЗ), а
    ТЗ п. 5.6 говорит, что роль даёт *умолчания* подписок, а не жёсткую
    привязку: тонкая настройка живёт в `Subscription`, а не в новых ролях.

    Значение пишется в claim `role` токена, поэтому перечень — единственный
    источник истины и для авторизации, и для домена.
    """

    L1 = "l1"
    """Техподдержка. Прокси для любого уведомления: разбирает сама либо
    передаёт на L2."""

    L2 = "l2"
    """Специалист. Решает то, что не решил L1."""

    MANAGER = "manager"
    """Должен быть в курсе. Read-only: получает ту же рассылку, что L2, но в
    разборе не участвует."""

    ADMIN = "admin"
    """CRUD пользователей, интеграций, таблиц severity и лестницы эскалации.
    На проблемы не реагирует вовсе."""

    @property
    def can_acknowledge(self) -> bool:
        """Может ли роль взять проблему в работу.

        Свойство роли, а не проверка на стороне API, по той же причине, по
        которой закрытие требует причины внутри агрегата: правило обязано
        держаться для всех входов — HTTP, чат-бот (п. 6.2), будущий CLI.
        """
        return self in (Role.L1, Role.L2)

    @property
    def is_engineer(self) -> bool:
        """Кто ведёт регламентные работы и, значит, может объявить окно
        обслуживания (п. 4.5 — это действие инженера, не администратора)."""
        return self in (Role.L1, Role.L2)
