"""Объект мониторинга — то, что сломалось."""

from dataclasses import dataclass


def normalize(name: str) -> str:
    """Каноническая форма имени объекта.

    Одна функция на весь домен, потому что имя объекта сравнивается в трёх
    местах — fingerprint, окно обслуживания, поиск оператора, — и они обязаны
    сходиться. Источники расходятся в том, зовётся ли хост «DB-PROD-03» или
    «db-prod-03», и это не должно расщеплять одну проблему на две или
    промахиваться мимо объявленного регламента.
    """
    return name.strip().lower()


@dataclass(frozen=True, slots=True)
class Asset:
    """Скважина, сервер, коммутатор — `object` из payload п. 2.1 ТЗ.

    Намеренно отделён от `Integration`: Zabbix — это *кто прислал* сигнал, а
    скважина — *о чём* сигнал. Отношение между ними один ко многим, и склеивать
    их нельзя. Fingerprint (п. 4.1) состоит из обоих сразу, так что при склейке
    одно из слагаемых перестало бы нести информацию; окно обслуживания
    привязано к объекту, а лимит приёма — к интеграции, и заглушить скважину на
    регламент означало бы заглушить весь Zabbix.

    Value object без собственного id: объект опознаётся именем в пределах
    системы мониторинга, а отдельный жизненный цикл ему не нужен — платформа
    объекты не заводит, а узнаёт о них из событий.
    """

    name: str
    type: str

    @property
    def key(self) -> str:
        """Имя в канонической форме — для сравнений и построения fingerprint."""
        return normalize(self.name)
