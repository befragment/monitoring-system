"""Сбои прикладного уровня.

Отличаются от доменных (`app.domain.errors`) тем, что описывают не нарушенное
бизнес-правило, а невозможность выполнить сценарий: не нашли, не имеешь права,
источник неизвестен. Доменные ошибки сервис пропускает наружу как есть — они
уже сформулированы точнее, чем это сделал бы пересказ.

Как и домен, ничего не знают про HTTP. Раскладывает по кодам слой handler.
"""


class ApplicationError(Exception):
    """Базовый класс, чтобы handler мог поймать семейство разом."""


class NotFound(ApplicationError):
    """Объекта с таким идентификатором нет."""


class PermissionDenied(ApplicationError):
    """Роль не позволяет выполнить действие.

    Отдельно от доменного `AcknowledgeNotPermitted`: тот про конкретное правило
    жизненного цикла проблемы, этот — про доступ к сценарию вообще (чужая
    подписка, админский CRUD).
    """


class AuthenticationFailed(ApplicationError):
    """Каталог не подтвердил учётные данные.

    Намеренно одна ошибка на все случаи: «нет такого пользователя» и «неверный
    пароль» обязаны быть неразличимы снаружи, иначе форма входа превращается в
    оракул для перебора логинов.
    """


class UnknownIntegration(ApplicationError):
    """Событие пришло от источника, которого нет в справочнике, либо он выключен.

    Не тихое игнорирование: неизвестный `source_system` означает либо опечатку в
    настройке источника, либо чужой трафик на эндпоинте, и оба случая надо
    видеть.
    """


class IntakeThrottled(ApplicationError):
    """Источник превысил свой лимит приёма (п. 2.5).

    Наружу это не должно превращаться в 429: источник начнёт ретраить и сделает
    только хуже. ТЗ требует уводить избыток в отложенную обработку, поэтому
    исключение сигнализирует «принято, но не в общий поток».
    """


