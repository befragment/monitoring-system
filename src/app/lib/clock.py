"""Часы.

Единственный источник «сейчас» для сервисов. Смысл в том, чтобы время было
аргументом, а не глобальным `datetime.now()`: тик эскалации, окна лимитов и
отметки доставки тогда проверяются подстановкой других часов, без патчинга
модуля и без `sleep` в тестах.

Доменные мутаторы и без того принимают момент явно — этот порт нужен там, где
решение «какой момент считать текущим» принимает сервис.
"""

from datetime import UTC, datetime
from typing import Protocol


class ClockInterface(Protocol):
    def now(self) -> datetime: ...


class Clock:
    """Системные часы. Всегда в UTC.

    Наивный `datetime.now()` без зоны здесь недопустим: значения уходят в
    колонки `timestamptz` и сравниваются со временем событий от источников,
    которые присылают смещение. Смешать наивное с aware — получить `TypeError`
    в середине обработки шторма.
    """

    def now(self) -> datetime:
        return datetime.now(UTC)


class FixedClock:
    """Часы, которые стоят и двигаются вручную.

    Живут рядом с рабочей реализацией намеренно: подделка времени нужна не
    только тестам, но и локальному прогону сценариев эскалации, где ждать
    тридцать минут никто не станет.
    """

    def __init__(self, now: datetime) -> None:
        self._now = now

    def now(self) -> datetime:
        return self._now

    def advance(self, delta) -> None:
        self._now += delta
