"""Сбои уровня домена.

Описывают нарушенные бизнес-правила, а не проблемы HTTP: домен не должен знать,
что его дёргают из API. Слой handler сам раскладывает их по статус-кодам
(InvalidTransition -> 409, CloseReasonRequired -> 422 и так далее).
"""


class DomainError(Exception):
    """Базовый класс, чтобы сервисный слой мог поймать всё семейство разом."""


class InvalidTransition(DomainError):
    """Переход, которого нет в машине состояний из п. 6.1 ТЗ."""


class ProblemClosed(InvalidTransition):
    """Закрытая проблема — терминальное состояние.

    Дедупликация привязана к *активным* проблемам, поэтому повторное событие
    после закрытия обязано открыть новую проблему, а не воскресить старую.
    Именно это оставляет ответимыми вопросы «сколько раз это ломалось за
    неделю» и «сколько времени чинили»: каждая поломка — отдельный эпизод со
    своей длительностью, а флапающий объект виден как флапающий.
    """


class AlreadyAcknowledged(InvalidTransition):
    """Двое инженеров нажали Acknowledge на одной проблеме.

    Сознательно не молчаливый no-op: второму нужно сообщить, кто уже взял
    проблему, иначе оба решат, что чинит другой.
    """


class AcknowledgeNotPermitted(DomainError):
    """Роль не имеет права брать проблему в работу.

    Manager подписан на ту же рассылку, что L2, и видит проблему в интерфейсе,
    но кнопки «взять в работу» у него нет; admin не участвует в разборе вовсе.
    Проверка живёт в агрегате, а не в схеме запроса, потому что вход не один:
    API, чат-бот (п. 6.2), возможный CLI.
    """


class HandoverNotAllowed(InvalidTransition):
    """Передача на L2 невозможна: проблема уже на L2 либо закрыта.

    Передача — односторонняя операция. Возврат L2 → L1 намеренно отсутствует:
    он позволил бы гонять проблему между уровнями, обнуляя ощущение
    ответственности, а лестница эскалации всё равно не умеет ходить назад.
    """


class CloseReasonRequired(DomainError):
    """П. 6.1: закрытие проблемы без указания причины недопустимо."""


class FingerprintMismatch(DomainError):
    """Событие применили к проблеме, которой оно не принадлежит.

    Достижимо только через баг в сервисном слое, но агрегат отказывается молча
    всасывать чужие события в свои счётчики.
    """
