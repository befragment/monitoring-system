"""Лестница эскалации, выраженная данными, а не ветвлениями в коде.

Отступление от п. 5.4 ТЗ, зафиксированное осознанно: ТЗ начинает цепочку с
«личного оповещения исполнителю», но в момент рождения проблемы исполнителя не
существует — его назначает тот, кто первым нажмёт Acknowledge. Поэтому все
ступени адресованы роли или командному каналу, а не персоне.

Побочный эффект: таблица дежурств (п. 5.5) не нужна для запуска, потому что ни
одна ступень не требует выбрать одного человека из группы. Цена — критерий
п. 5.7 «в сообщении эскалации указан реальный дежурный из таблицы» на MVP не
закрывается. Понадобится, если вторая ступень когда-нибудь станет персональной.
"""

from dataclasses import dataclass
from datetime import datetime, timedelta
from enum import StrEnum

from app.domain.severity import Severity


class EscalationTarget(StrEnum):
    """Кого оповещают на каждой ступени лестницы.

    Ступени 2 и 3 различаются не получателем, а *адресацией*: сначала одно
    сообщение в общий канал команды L2, затем персонально каждому активному L2.
    Без этого различия третья ступень была бы дословным повтором второй.
    """

    L1_CHANNEL = "l1_channel"
    """Командный канал техподдержки — первое оповещение по любой проблеме."""

    L2_CHANNEL = "l2_channel"
    """Командный канал специалистов: L1 не отреагировал."""

    L2_BROADCAST = "l2_broadcast"
    """Персонально каждому активному L2. Последняя ступень: реакции нет ни у
    кого, и молчание общего канала больше не может считаться случайностью."""


@dataclass(frozen=True, slots=True)
class EscalationStep:
    target: EscalationTarget
    # Отсчитывается от момента появления проблемы, а не от предыдущего шага.
    # Абсолютные смещения читаются понятнее («всех L2 поднимают на 30-й минуте»)
    # и означают, что задержавшийся шаг не сдвигает все последующие.
    after: timedelta


@dataclass(frozen=True, slots=True)
class EscalationPolicy:
    """Упорядоченная лестница, вычисляемая по прошедшему времени и по тому,
    сколько ступеней уже пройдено.

    Оставлена чистым value object без ввода-вывода и без состояния: счётчик
    пройденных ступеней живёт на `Problem`, иначе воркер после перезапуска либо
    разослал бы всю лестницу заново, либо не разослал бы ничего. Проверка
    критерия п. 5.7 тогда не требует патчинга часов — достаточно двух datetime.
    """

    steps: tuple[EscalationStep, ...]
    # ОТКРЫТЫЙ ВОПРОС (см. new.md, «Осталось решить»): с какой критичности
    # лестница вообще включается. Смысл решён — warning про диск никого не
    # будит, падение прода будит, — но порог числом ещё не назван, поэтому
    # None означает «пока применяется ко всем». Когда порог появится, это
    # правка одной строки конфигурации, а не модели.
    #
    # Второй вопрос той же темы: если проблема родилась как WARNING и доросла до
    # CRITICAL, откуда считать смещения — от появления проблемы или от момента
    # роста критичности. Вызывающий передаёт `opened_at` сам, так что политика
    # переживёт любой ответ.
    min_severity: Severity | None = None

    def applies_to(self, severity: Severity) -> bool:
        """Подлежит ли проблема такой критичности эскалации вообще.

        Отключается именно эскалация, а не учёт: проблема создаётся и
        доставляется по подпискам на любом уровне — просто никого не будят.
        """
        return self.min_severity is None or severity >= self.min_severity

    def due_step(
        self,
        opened_at: datetime,
        now: datetime,
        steps_taken: int,
    ) -> EscalationStep | None:
        """Следующий шаг к отправке или None, если время ещё не пришло.

        Возвращает по одному шагу, а не список: если воркер лежал час, то при
        возобновлении нельзя вывалить человеку в телефон всю лестницу разом —
        каждая отправка получает свой проход, а Acknowledge между ними
        останавливает цепочку.
        """
        if steps_taken >= len(self.steps):
            return None

        candidate = self.steps[steps_taken]
        if now - opened_at >= candidate.after:
            return candidate
        return None

    def is_exhausted(self, steps_taken: int) -> bool:
        """Эскалировать больше некому — сервисный слой должен это показать, а не
        дать проблеме молча висеть на верхней ступени."""
        return steps_taken >= len(self.steps)


# Лестница проекта: L1 сразу, через 15 минут молчания — канал L2, ещё через 15
# (30 от появления проблемы) — персонально всем L2.
#
# Manager ступенью не является: он подписан на ту же рассылку, что L2, и узнаёт
# о проблеме сразу, поэтому эскалировать к нему нечего. Admin не участвует в
# разборе вовсе.
DEFAULT_ESCALATION_POLICY = EscalationPolicy(
    steps=(
        EscalationStep(EscalationTarget.L1_CHANNEL, after=timedelta(0)),
        EscalationStep(EscalationTarget.L2_CHANNEL, after=timedelta(minutes=15)),
        EscalationStep(EscalationTarget.L2_BROADCAST, after=timedelta(minutes=30)),
    ),
)
