"""Шаг 1 — подключённая система мониторинга как сущность.

До этого источник жил в модели голой строкой `source_system`, разбросанной по
событию, проблеме и таблице соответствий. Строка не может хранить то, что у
источника на самом деле есть: способ подключения, адрес, креды, свою шкалу
severity и свой лимит приёма. Отсюда отдельный агрегат.
"""

import uuid
from dataclasses import dataclass
from enum import StrEnum

from app.domain.severity import SeverityMapping
from app.domain.suppression import DEFAULT_SOURCE_RATE_LIMIT, RateLimit


class ConnectionType(StrEnum):
    """П. 1.2 ТЗ — как именно данные попадают в платформу.

    Хранится как свойство интеграции, потому что п. 1.3 требует фиксировать
    способ подключения для каждого источника в документации, а держать это
    отдельной таблицей в вики — гарантированно разъехаться с реальностью.
    """

    PUSH = "push"
    """Источник сам присылает событие (Zabbix через webhook-медиатип)."""

    PULL = "pull"
    """Платформа опрашивает источник по расписанию (SNMP-опрос)."""


@dataclass(frozen=True, slots=True)
class Integration:
    """Zabbix, SolarWinds, AggreGate, Saymon, Prometheus, тестовый генератор.

    Не путать с `Asset`: интеграция — это *кто прислал* сигнал, объект — *о чём*
    сигнал. Одна инсталляция Zabbix наблюдает тысячи объектов, то есть отношение
    один ко многим. Из него следует всё разделение обязанностей: таблица
    severity и лимит приёма принадлежат интеграции (иначе таблиц понадобилось бы
    столько же, сколько объектов), а окно обслуживания — объекту.

    Frozen: это конфигурация, которую правит админ через CRUD, а не сущность с
    жизненным циклом. Изменение — замена записи целиком, а не мутация на месте,
    и в аудит уходит `SETTINGS_CHANGED`.
    """

    id: uuid.UUID
    # То, что приходит в поле `source_system` payload'а п. 2.1, и то, что входит
    # в fingerprint (п. 4.1). Fingerprint строится по slug, а не по id, по двум
    # причинам: событие приносит именно строку, и подстановка uuid потребовала бы
    # обращения к справочнику на каждом входящем событии — то есть похода в базу
    # на самом горячем пути системы (п. 2.3: до 50 событий/сек на пике).
    slug: str
    title: str
    connection: ConnectionType
    # Своя таблица на каждую интеграцию (п. 3.1): «average» означает вполне
    # конкретную вещь в Zabbix и ничего в Prometheus.
    severity_mapping: SeverityMapping
    # П. 2.5 — лимит числа событий, принимаемых от одного источника. Именно от
    # источника: «Zabbix залил нас» — это свойство интеграции, а не объекта.
    intake_limit: RateLimit = DEFAULT_SOURCE_RATE_LIMIT
    # Для pull — что опрашивать; для push — необязателен, инициатива на той
    # стороне.
    endpoint: str | None = None
    # *Ссылка* на секрет в хранилище, а не сам секрет. Домен не должен уметь
    # предъявить токен: он только знает, под каким именем его спросить.
    credentials_ref: str | None = None
    # Выключенная интеграция перестаёт приниматься, но её проблемы и история
    # остаются — так же, как неактивный пользователь не теряет свои подписки.
    is_enabled: bool = True

    def __post_init__(self) -> None:
        if not self.slug.strip():
            raise ValueError("an integration must have a non-empty slug")

    @property
    def is_polled(self) -> bool:
        """Нужен ли этой интеграции воркер опроса (п. 1.2.2)."""
        return self.connection is ConnectionType.PULL
